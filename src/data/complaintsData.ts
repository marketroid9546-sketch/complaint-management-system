// Combine base complaints with structured expansion across all 22 locations
export function generateFullMockComplaints(locations: { code: string; entity: string; name: { en: string; ur: string } }[]): Complaint[] {
  const result: Complaint[] = [...INITIAL_COMPLAINTS];
  const prefixes = ['7A', '3B', '9C', '2D', '5E', '8F', '1G', '4H', '6J', '2K', '7M', '9N', '3P', '8Q', '5R', '1S', '6T', '4U', '8V', '2W', '9X', '3Y'];

  // Fill up to 55 complaints
  let index = 0;
  while (result.length < 55) {
    const loc = locations[index % locations.length];
    const sample = SAMPLE_ISSUES[index % SAMPLE_ISSUES.length];
    const ticketId = `MTJ-${prefixes[index % prefixes.length]}${Math.floor(1000 + (index * 137) % 9000)}`;

    const ageHours = Math.round((sample.ageDays + (index % 3) * 0.4) * 24);
    const date = new Date(Date.now() - ageHours * 3600 * 1000).toISOString();

    const ackHours = sample.track === 'SAFEGUARDING' ? 4 : sample.severity === 'CRITICAL' ? 6 : 24;
    const resolveHours = sample.track === 'SAFEGUARDING' ? 24 : 72;
    const ackDeadline = new Date(new Date(date).getTime() + ackHours * 3600 * 1000).toISOString();
    const resolveDeadline = new Date(new Date(date).getTime() + resolveHours * 3600 * 1000).toISOString();

    const isOverdue = sample.isOverdue || ageHours > resolveHours;

    result.push({
      id: ticketId,
      entity: loc.entity as any,
      locationCode: loc.code,
      locationName: loc.name,
      category: sample.category,
      track: sample.track,
      submitterType: sample.submitter,
      isAboutPersonInCharge: false,
      text: sample.text,
      voiceNote: sample.hasVoice
        ? {
            durationSeconds: 20 + (index * 7) % 35,
            recordedAt: date,
          }
        : undefined,
      photos: sample.hasPhoto
        ? [
            'data:image/svg+xml;utf8,<svg xmlns="http://www.w3.org/2000/svg" width="200" height="200" viewBox="0 0 200 200"><rect fill="%23e0f2fe" width="200" height="200"/><text x="100" y="105" fill="%230369a1" font-size="14" text-anchor="middle" font-family="sans-serif">Photo Evidence ' +
              (index + 1) +
              '</text></svg>',
          ]
        : [],
      isAnonymous: sample.isAnon,
      contactInfo: sample.isAnon
        ? undefined
        : {
            name: ['Zubair Khan', 'Muhammad Bilal', 'Farzana Bibi', 'Tanveer Ahmed', 'Nadia Parveen', 'Kashif Mehmood'][index % 6],
            phone: `030${index % 5}-${1000000 + index * 12345}`,
            notifyWhatsApp: index % 2 === 0,
          },
      status: sample.status,
      severity: sample.severity,
      createdAt: date,
      ackDeadlineHours: ackHours,
      resolveDeadlineHours: resolveHours,
      ackDeadlineAt: ackDeadline,
      resolveDeadlineAt: resolveDeadline,
      acknowledgedAt: sample.status !== 'New' ? new Date(new Date(date).getTime() + 2 * 3600 * 1000).toISOString() : undefined,
      resolvedAt: sample.status === 'Resolved' || sample.status === 'Closed' ? new Date(new Date(date).getTime() + 36 * 3600 * 1000).toISOString() : undefined,
      ownerRole: sample.ownerRole,
      ownerName: sample.ownerName,
      watcherRoles: sample.track === 'SAFEGUARDING' ? ['CEO'] : sample.track === 'CONFIDENTIAL' ? ['CEO'] : ['Regional Manager'],
      watchers: sample.track === 'SAFEGUARDING' ? ['Dr. Tariq Jamil'] : ['Naveed Akram'],
      escalationLevel: isOverdue ? Math.max(sample.escalation, 1) : 0,
      isOverdue: isOverdue,
      matchedRuleId: 'rule-gen',
      rejectionReason: sample.status === 'Rejected' ? 'Out of organizational jurisdiction or policy guidelines.' : undefined,
      internalNotes: [
        {
          id: `in-gen-${index}`,
          author: sample.ownerName,
          role: sample.ownerRole,
          text: `Routine case logged for branch action. Case status evaluated as ${sample.status}.`,
          timestamp: new Date(new Date(date).getTime() + 3600 * 1000).toISOString(),
        },
      ],
      publicUpdates: [
        {
          id: `pu-gen-${index}`,
          textUr: `شکایت درج ہو چکی ہے اور متعلقہ انچارج (${sample.ownerRole}) کو کارروائی کے لیے بھیج دی گئی ہے۔`,
          textEn: `Complaint registered and assigned to ${sample.ownerRole} for appropriate departmental review.`,
          timestamp: new Date(new Date(date).getTime() + 3600 * 1000).toISOString(),
        },
      ],
      auditTimeline: [
        {
          id: `aud-gen-1-${index}`,
          eventType: 'CREATED',
          actor: 'System Ingress',
          role: sample.submitter,
          details: `Ticket registered under ${sample.track} track`,
          timestamp: date,
        },
        ...(sample.track === 'SAFEGUARDING'
          ? [
              {
                id: `aud-gen-view-${index}`,
                eventType: 'VIEWED' as const,
                actor: 'Ayesha Siddiqui',
                role: 'Child Protection Officer',
                details: 'Audit log: Safeguarding record accessed by CPO',
                timestamp: new Date(new Date(date).getTime() + 4000 * 1000).toISOString(),
              },
            ]
          : []),
      ],
    });

    index++;
  }

  return result;
}
